# LESSON NOTES
# Python is a programming language used to
# give instructions to a computer.
#
# The print() function displays information
# in the terminal.
#
# Strings are text surrounded by quotation marks.
# Integers are whole numbers.
# Comments begin with # and are ignored by Python.


# EXAMPLE 1: Printing text

print("Hello, World!")
print("Welcome to Python programming.")


# EXAMPLE 2: Printing numbers

print(10)
print(25)
print(100)


# EXAMPLE 3: Printing multiple values

print("My name is", "Student")
print("Coding Camp Day:", 1)


# EXAMPLE 4: Printing calculations

print(5 + 5)
print(10 - 3)
print(4 * 2)
print(20 / 5)


# EXAMPLE 5: Printing blank lines

print()
print("End of Day 1 examples.")


# WHAT I LEARNED
# 1. Python executes statements in order.
# 2. print() displays information.
# 3. Strings require quotation marks.
# 4. Numbers can be printed without quotation marks.
# 5. Python can perform calculations.
