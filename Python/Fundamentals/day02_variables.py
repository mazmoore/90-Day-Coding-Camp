# LESSON NOTES
# A variable is a name that refers to a value.
#
# Variables allow programs to store information
# and reuse it throughout the program.
#
# Python determines the data type automatically
# based on the assigned value.
#
# The = symbol is used for assignment.


# EXAMPLE 1: Creating variables

name = "Alex"
age = 23
school = "New Mexico State University"

print(name)
print(age)
print(school)


# EXAMPLE 2: String data type (str)

first_name = "Alex"
career = "Cybersecurity Analyst"

print(first_name)
print(career)
print(type(first_name))


# EXAMPLE 3: Integer data type (int)

student_age = 23
coding_days = 45

print(student_age)
print(coding_days)
print(type(student_age))


# EXAMPLE 4: Float data type (float)

gpa = 3.5
price = 29.99

print(gpa)
print(price)
print(type(price))


# EXAMPLE 5: Boolean data type (bool)

is_student = True
has_graduated = False

print(is_student)
print(has_graduated)
print(type(is_student))


# EXAMPLE 6: Updating variables

score = 50
print("Original score:", score)

score = 75
print("Updated score:", score)


# EXAMPLE 7: Combining variables

first_name = "Alex"
last_name = "Smith"

print("Full name:", first_name, last_name)


# EXAMPLE 8: Variable naming rules

student_name = "Alex"
student_age = 23
course_1 = "Python"

print(student_name)
print(student_age)
print(course_1)


# WHAT I LEARNED
# 1. Variables store references to values.
# 2. Strings represent text.
# 3. Integers represent whole numbers.
# 4. Floats represent decimal numbers.
# 5. Booleans represent True or False.
# 6. Variables can be reassigned.
# 7. Variable names are case-sensitive.
